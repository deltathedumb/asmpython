# probe24: ord, chr, hex, oct, bin, format
print(ord("A"))        # 65
print(ord("a"))        # 97
print(chr(65))         # A
print(chr(97))         # a
print(hex(255))        # 0xff
print(oct(8))          # 0o10
print(bin(5))          # 0b101
print(format(42, "b")) # 101010
print(format(42, "x")) # 2a
print(format(42, "o")) # 52
