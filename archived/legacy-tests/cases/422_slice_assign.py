# expect:
# [0, 10, 20, 3, 4]
# [10, 20, 30, 40, 50, 6, 7, 8, 9]
# [1, 2, 3, 99, 5]
# [99, 2, 3, 4, 5]
# [1, 2, 3, 4, 88]

xs = [0, 1, 2, 3, 4]
xs[1:3] = [10, 20]
print(xs)

ys = [1, 2, 3, 4, 5, 6, 7, 8, 9]
ys[0:5] = [10, 20, 30, 40, 50]
print(ys)

zs = [1, 2, 3, 4, 5]
zs[3:4] = [99]
print(zs)

# slice with omitted start/stop
ws = [1, 2, 3, 4, 5]
ws[:1] = [99]
print(ws)

vs = [1, 2, 3, 4, 5]
vs[-1:] = [88]
print(vs)
